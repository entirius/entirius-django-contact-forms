class BookingConfigFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = BookingConfig

    channel = factory.SubFactory(ChannelFactory)
    enabled = True
    service_account_credentials_path = "/app/credentials/sa.json"
    impersonate_email = factory.LazyAttribute(lambda o: f"bookings-{o.channel.idx}@example.com")
    calendar_id = "primary"
    timezone = "Europe/Warsaw"

    @factory.post_generation
    def time_windows(obj, create, extracted, **kwargs):
        """Auto-create one default 9:00-17:00 window unless `time_windows=[...]` is passed.

        Tests that need different windows pass: ``BookingConfigFactory(time_windows=[
            {"start_time": time(10, 0), "end_time": time(12, 30)},
            {"start_time": time(16, 0), "end_time": time(17, 0)},
        ])``.
        """
        if not create:
            return
        if extracted:
            for i, w in enumerate(extracted):
                BookingTimeWindow.objects.create(
                    booking_config=obj, order=w.get("order", i), **{k: v for k, v in w.items() if k != "order"}
                )
        else:
            BookingTimeWindow.objects.create(booking_config=obj, order=0, start_time=time(9, 0), end_time=time(17, 0))


