def enable_global_settings(*, bookings: bool = False, google_ads: bool = False) -> ContactFormsSettings:
    s = ContactFormsSettings.load()
    s.bookings_enabled = bookings
    s.google_ads_enabled = google_ads
    s.save()
    return s
